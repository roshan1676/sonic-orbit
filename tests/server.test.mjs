import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, writeFile, rm, rmdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createApp, parseRange } from '../server.mjs';

test('byte ranges support seeking and reject invalid requests', () => {
  assert.deepEqual(parseRange('bytes=3-6', 10), { start: 3, end: 6 });
  assert.deepEqual(parseRange('bytes=-3', 10), { start: 7, end: 9 });
  assert.deepEqual(parseRange('bytes=5-', 10), { start: 5, end: 9 });
  assert.deepEqual(parseRange('bytes=0-99', 10), { start: 0, end: 9 });
  for (const range of ['bytes=10-', 'bytes=5-2', 'bytes=-0', 'bytes=0-1,3-4', 'bytes=-', 'bad']) assert.throws(() => parseRange(range, 10));
});
test('local server protects paths and media access while serving seekable files', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'sound360-test-'));
  const path = join(directory, 'sample.mp4'); await writeFile(path, '0123456789');
  const server = await createApp({ initialPath: path, trackingPort: 0 });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { await new Promise(resolve => { server.close(resolve); server.closeAllConnections(); }); await rm(path); await rmdir(directory); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const session = await (await fetch(base + '/api/session')).json();
  assert.equal(session.app.name,'SonicOrbit');assert.equal(session.app.version,'0.1.0-alpha.2');assert.equal(typeof session.features.aiSeparation,'boolean');
  assert.equal(session.initial.path, undefined); assert.equal(session.initial.name, 'sample.mp4');
  const response = await fetch(base + session.initial.url, { headers: { Range: 'bytes=3-6' } });
  assert.equal(response.status, 206); assert.equal(await response.text(), '3456');
  assert.equal(response.headers.get('content-range'), 'bytes 3-6/10');
  assert.equal((await fetch(base + session.initial.url, { method: 'HEAD' })).headers.get('content-length'), '10');
  assert.equal((await fetch(base + session.initial.url, { headers: { Range: 'bytes=99-' } })).status, 416);
  for (const path of ['/.git/config', '/server.mjs', '/package.json', '/media/unknown', '/vendor/../package.json']) assert.equal((await fetch(base + path)).status, 404);
  assert.equal((await fetch(base + '/api/open', { method: 'POST', headers: { Origin: base, 'Content-Type': 'application/json' }, body: JSON.stringify({ path }) })).status, 403);
  assert.equal((await fetch(base + '/api/open', { method: 'POST', headers: { Origin: 'https://example.org', 'X-360-Token': session.token }, body: JSON.stringify({ path }) })).status, 403);
  const opened = await fetch(base + '/api/open', { method: 'POST', headers: { Origin: base, 'X-360-Token': session.token }, body: JSON.stringify({ path }) });
  assert.equal(opened.status, 200);
  assert.match((await fetch(base)).headers.get('permissions-policy'), /microphone=\(\)/);
  assert.equal((await fetch(base+'/api/tracking/start',{method:'POST'})).status,403);
  assert.equal((await fetch(base+'/api/tracking/model',{method:'POST'})).status,403);
  assert.equal((await fetch(base+'/api/shutdown',{method:'POST'})).status,403);
  assert.match((await fetch(base+'/brand/mark.svg')).headers.get('content-type'),/image\/svg/);
  assert.equal((await fetch(base+'/api/stems/'+session.initial.id,{method:'POST'})).status,403);
  assert.equal((await(await fetch(base+'/api/stems/'+session.initial.id)).json()).state,'idle');
  assert.equal((await fetch(base+'/stems/'+session.initial.id+'/vocals.wav')).status,404);
  assert.equal((await fetch(base+'/stems/'+session.initial.id+'/../../server.mjs')).status,404);
  assert.equal((await fetch(base+'/api/stems/abcd')).status,404);
  for(const path of ['/sdk/spatial-audio.js','/sdk/source-geometry.js'])assert.equal((await fetch(base+path)).status,200);
  const trackerHeaders = { Origin:base,'X-360-Token':session.token };
  const trackerStart = await (await fetch(base+'/api/tracking/start',{method:'POST',headers:trackerHeaders})).json();
  assert.equal(trackerStart.enabled,true); assert.ok(trackerStart.port > 0);
  const trackerStop = await (await fetch(base+'/api/tracking/stop',{method:'POST',headers:trackerHeaders})).json();
  assert.equal(trackerStop.enabled,false);
});
